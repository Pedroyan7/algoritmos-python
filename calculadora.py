print("### CALCULADORA PYTHON ###" )


def adicao(num1, num2):
    soma = num1 + num2
    return soma

print("resultado da soma: ", adicao(16,2))

def subtrair(num1, num2):
    subtracao = num1 - num2
    return subtracao

print("resultado da subtraçao: ", subtrair(16,2))

def multiplicar(num1, num2):
    multiplicacao = num1 * num2
    return multiplicacao

print("resultado da multiplicaçao: ", multiplicar(16,2))

def dividir(num1, num2):
    divisao = num1 / num2
    return divisa

print("resultado da divisao: ", dividir(16,2))



